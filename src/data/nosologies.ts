/** Шаблон по коду МКБ-10 из амбулаторного приёма. */
export function templateForIcd(icd: string): DayTemplate {
  const c = (icd || '').trim().toUpperCase();
  if (!c) return 'empty';
  // самый длинный подходящий префикс: L73.2 → гидраденит, L73.8 → фолликулит
  let best: NosDef | null = null;
  let len = 0;
  for (const n of NOSOLOGIES) for (const p of n.icd) if (c.startsWith(p) && p.length > len) { best = n; len = p.length; }
  return best?.key ?? 'empty';
}

/** Форма нозологии по коду МКБ-10 (L40.4 → каплевидная, L63 → гнёздная). */
export function formForIcd(key: string, icd: string): string | undefined {
  const d = nosDef(key);
  if (!d.forms) return undefined;
  const c = (icd || '').trim().toUpperCase();
  return d.forms.find((f) => f.icd?.some((p) => c.startsWith(p)))?.v ?? d.forms[0].v;
}

/** Название протокола МЗ для нозологии и формы. */
export function guideFor(key: string, form?: string): string | null {
  const d = nosDef(key);
  const f = d.forms?.find((x) => x.v === form);
  return f?.guide ?? d.guide;
}

