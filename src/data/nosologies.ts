export function stdInGuide(g: { drugs: { g: string; n: string }[] } | null, r: Pick<DayRow, 'sec' | 'ru'>): boolean | null {
  if (!g || !r.ru.trim()) return null;
  const name = r.ru.toLowerCase().replace(/ё/g, 'е');
  if (r.sec === 'phys') {
    const hit = PROC.find(([re]) => re.test(name));
    return hit ? g.drugs.some((d) => d.g === 'procedure' && hit[1].test(d.n)) : false;
  }
  const keys = INN.filter(([re]) => re.test(name)).map(([, k]) => k);
  if (!keys.length) return false;
  return keys.some((k) => g.drugs.some((d) => d.g !== 'procedure' && d.n.toLowerCase().replace(/ё/g, 'е').includes(k)));
}

// ---------- подсказки к строкам (только на экране) ----------
export interface NosHint { kind: 'warn' | 'info'; ru: string; uz: string }

export function nosHints(r: DayRow, age: number | null, sex: 'M' | 'F' | ''): NosHint[] {
  const n = `${r.ru} ${r.uz}`.toLowerCase();
  const out: NosHint[] = [];
  const kid = age !== null && age < 12;
  if (/ацикловир|инвиреп/.test(n)) out.push({ kind: 'info', ru: 'При назначении из-за ВЭБ нужно подтверждение инфекции (ИФА / ПЦР) — отметьте анализ «ВЭБ».', uz: 'ЭБВ сабабли тайинланса, инфекция тасдиғи керак (ИФА / ПЦР) — «ЭБВ» таҳлилини белгиланг.' });
  if (/доксилан|доксицикл/.test(n)) {
    if (age !== null && age < 8) out.push({ kind: 'warn', ru: 'Доксициклин детям до 8 лет не назначается.', uz: 'Доксициклин 8 ёшгача болаларга тайинланмайди.' });
    out.push({ kind: 'info', ru: 'Повышает чувствительность к свету — осторожно с UVB и фототерапией в этом курсе.', uz: 'Ёруғликка сезувчанликни оширади — шу курсдаги UVB ва фототерапияда эҳтиёт бўлинг.' });
  }
  if (/трихопол|метогил|метронидаз/.test(n)) out.push({ kind: 'info', ru: 'На печати будет сноска: алкоголь во время лечения запрещён.', uz: 'Варақада изоҳ бўлади: даволаниш вақтида спиртли ичимлик мумкин эмас.' });
  if (/цефтриакс|пенициллин|лидаза|новокаин/.test(n)) out.push({ kind: 'warn', ru: 'Только после пробы на переносимость. Проверьте аллергию в карте пациента.', uz: 'Фақат синамадан кейин. Бемор картасида аллергияни текширинг.' });
  if (/плаквенил|гидроксихлорох/.test(n)) out.push({ kind: 'info', ru: 'При приёме дольше месяца — осмотр офтальмолога.', uz: 'Бир ойдан ортиқ ичилса — офтальмолог кўриги.' });
  if (/дерм[оа]вейт|клобетазол/.test(n)) out.push(isChild(age)
    ? { kind: 'warn', ru: 'Сильный гормон: детям — с осторожностью, коротким курсом; не на лицо и складки.', uz: 'Кучли гормон: болаларга — эҳтиёткорлик билан, қисқа курс; юз ва бурмаларга эмас.' }
    : { kind: 'info', ru: 'Не наносить на лицо и складки.', uz: 'Юз ва бурмаларга суртилмасин.' });
  if (/дексаметазон\s*4|дексаметазон 4/.test(n)) out.push({ kind: 'info', ru: 'Только дни 1–3, дальше клетки пустые.', uz: 'Фақат 1–3 кунлари, кейин катаклар бўш.' });
  if (/миноксид[а-я]*\s*5\s*%/.test(n) && sex === 'F') out.push({ kind: 'warn', ru: 'Женщинам обычно назначают 2% — проверьте.', uz: 'Аёлларга одатда 2% тайинланади — текширинг.' });
  if (/миноксид[а-я]*\s*2\s*%/.test(n) && sex === 'M') out.push({ kind: 'info', ru: 'Мужчинам обычно назначают 5%.', uz: 'Эркакларга одатда 5% тайинланади.' });
  if (/вегас|лоранекс|дерилайф/.test(n)) out.push({ kind: 'info', ru: 'Состав препарата не подтверждён — отметка стандарта может быть неточной.', uz: 'Дори таркиби тасдиқланмаган — стандарт белгиси аниқ бўлмаслиги мумкин.' });
  if (kid && /азитромиц|ацикловир|доксилан|цефтриакс|трихопол|метогил|текназол/.test(n)) out.push({ kind: 'warn', ru: 'Ребёнку доза по массе тела — проверьте.', uz: 'Болага доза тана вазнига кўра — текширинг.' });
  return out;
}

