export function defaultLabs(key: string, rows: DayRow[], form?: string): string[] {
  const out = new Set(nosDef(key).labs);
  if (hasAntiviral(rows)) out.add('ebv');
  if (key === 'psor' && form === 'gutt') out.add('aslo');
  if (rows.some((r) => /изона|изотретино/i.test(r.ru))) { out.add('alt'); out.add('ast'); }
  return [...out];
}
