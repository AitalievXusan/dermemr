const KID_DROP = new Set(['unicenta', 'ginkgo', 'elforce', 'lipoic', 'aspero', 'biselen', 'normaven']);

/** Детские дозы и протокол МЗ для детей — как в утверждённых правилах витилиго и листе ребёнка с псориазом. */
function adaptAge(lines: Line[], age: number | null, chips: Chip[]): Line[] {
  const g = ageGroup(age);
  const kid = g === 'u7' || g === 'c';
  let out = lines;
  if (kid) {
    let hadStronger = false;
    out = out.filter((l) => {
      if (l.key.startsWith('stronger')) { hadStronger = true; return false; }
      return !KID_DROP.has(l.key);
    }).map((l) => {
      if (l.key === 'vitb') return { ...R.vitb('1,0', ['0,5', '1,0']), why: 'age' };
      if (l.key === 'vitd') return { ...R.vitd('2000'), why: 'age' };
      if (l.key === 'les') return { ...R.les('½'), why: 'age' };
      if (l.key === 'ascorbic') return { ...l, ru: l.ru.replace('2,0', '1,0'), uz: l.uz.replace('2,0', '1,0'), why: 'age' };
      return l;
    });
    if (hadStronger && g === 'c') {
      out.splice(Math.min(out.length, 1), 0, ln('drug', 'stronger', 'Натрия хлорид 0,9% — 100,0 + Стронгер нео 10,0, в/в капельно, ежедневно, №10', 'Натрий хлорид 0,9% — 100,0 + Стронгер нео 10,0, в/и томчилаб, ҳар куни, №10', D(), 'daily', 'age'));
    }
    const lastDrug = () => out.reduce((at, l, i) => (l.sec === 'drug' ? i : at), -1) + 1;
    if (!out.some((l) => l.key === 'antral')) out.splice(lastDrug(), 0, { ...R.antral(), why: 'kid' });
    if (!out.some((l) => l.key === 'bifolak')) out.splice(lastDrug(), 0, { ...R.bif(), why: 'kid' });
    chips.push({ ru: 'До 12 лет: без Юнисенты, гинкго, Эль-форса и гепатопротекторов; + Антрал, Бифолак; детские дозы', uz: '12 ёшгача: Юнисента, гинкго, Эль-форс ва гепатопротекторларсиз; + Антрал, Бифолак; болалар дозалари' });
  } else if (g === 't') {
    out = out.filter((l) => l.key !== 'ginkgo');
    chips.push({ ru: '12–17 лет: без гинкго', uz: '12–17 ёш: гинкгосиз' });
  } else {
    chips.push({ ru: age === null ? 'Год рождения не указан — взрослые дозы' : 'Взрослые дозы', uz: age === null ? 'Туғилган йили кўрсатилмаган — катталар дозаси' : 'Катталар дозаси' });
  }
  if (isChild(age)) {
    out = out.map((l) => (l.key === 'tacro' && /0[,.]1\s*%/.test(l.ru) ? { ...l, ru: l.ru.replace(/0[,.]1\s*%/, '0,03%'), uz: l.uz.replace(/0[,.]1\s*%/, '0,03%'), why: 'mz' } : l));
    if (out.some((l) => l.why === 'mz')) chips.push({ ru: 'Протокол МЗ: детям Такропик 0,03%', uz: 'ССВ протоколи: болаларга Такропик 0,03%' });
  }
  return out;
}

const STAGE_RU: Record<NosStage, T2> = { prog: { ru: 'прогрессирующая', uz: 'прогрессив' }, stat: { ru: 'ремиссия', uz: 'ремиссия' }, regr: { ru: 'регрессирующая', uz: 'регрессив' } };

/**
 * Собирает лист нозологии. custom — свой шаблон врача (строки вместо исходных); производные строки
 * (гормон по стадии, дексаметазон, миноксидил, процедуры) всё равно следуют панели конструктора.
 */
export function buildNos(opts: { key: DayTemplate; age: number | null; params: NosParams; custom?: CustomTemplate | null; prevStart?: string | null }): NosBuild {
  const { key, age, params } = opts;
  const def = nosDef(key);
  const b = base(key, params);
  let lines = b.lines;
  let afterT = b.after;
  const chips: Chip[] = [];
  if (opts.prevStart) chips.push({ ru: `Прошлый курс с ${ddmmyy(opts.prevStart)}`, uz: `Олдинги курс ${ddmmyy(opts.prevStart)} дан` });
  if (opts.custom?.rows.length) {
    const derived = new Set(['steroid', 'dex4', 'minox', 'proc', 'azithro', 'calcium', 'aevit', 'excimer']);
    const fresh = new Map(lines.filter((l) => derived.has(l.key)).map((l) => [l.key, l]));
    const mine: Line[] = opts.custom.rows.map((r) => ({ sec: r.sec, key: r.key || '', ru: r.ru, uz: r.uz, cells: r.cells, pk: r.pk }));
    lines = mine.flatMap((l) => (derived.has(l.key) ? (fresh.get(l.key) ? [fresh.get(l.key) as Line] : []) : [l]));
    for (const [k, l] of fresh) if (!lines.some((x) => x.key === k)) lines.push(l);
    lines = sortSections(lines);
    afterT = opts.custom.after;
    chips.push({ ru: `Ваш шаблон от ${ddmmyy(opts.custom.savedAt.slice(0, 10))}`, uz: `Сизнинг андозангиз (${ddmmyy(opts.custom.savedAt.slice(0, 10))})` });
  } else if (def.isNew) {
    chips.push({ ru: 'Новый шаблон: собран по протоколу МЗ РУз на каркасе клиники — проверьте строки', uz: 'Янги андоза: ЎзР ССВ протоколи ва клиника каркаси бўйича тузилди — қаторларни текширинг' });
  }
  chips.push(...b.chips);
  if (def.stages && params.stage && key !== 'psor' && key !== 'eczema') chips.push({ ru: `Стадия: ${STAGE_RU[params.stage].ru} — записывается в лист`, uz: `Босқич: ${STAGE_RU[params.stage].uz} — варақага ёзилади` });
  lines = adaptAge(lines, age, chips);
  if (lines.some((l) => l.key === 'acyclovir' || l.key === 'invirep')) chips.push({ ru: 'Противовирусное в шаблоне: при ВЭБ нужно подтверждение инфекции (анализ отмечен)', uz: 'Андозада вирусга қарши дори: ЭБВ бўлса, инфекция тасдиғи керак (таҳлил белгиланди)' });

  const rows: DayRow[] = lines.map((l) => ({
    id: rowId(), sec: l.sec, ru: l.ru, uz: l.uz, cells: l.cells.slice(0, COURSE_DAYS), std: null, pk: l.pk, auto: true, key: l.key, ...(l.why ? { why: l.why } : {}),
  }));
  const kid = ageGroup(age) === 'u7' || ageGroup(age) === 'c';
  const after: AfterRow[] = afterT
    .filter((a) => !kid || !/юнисент|гинкго|эль-форс|асперо|биселен|нормавен/i.test(a.ru))
    .map((a) => ({ id: rowId(), ru: kid ? a.ru.replace('5000 МЕ', '2000 МЕ') : a.ru, uz: kid ? a.uz.replace('5000 ХБ', '2000 ХБ') : a.uz, auto: true }));
  return { rows, after, chips };
}

function sortSections(lines: Line[]): Line[] {
  const order: DaySection[] = ['drug', 'top', 'phys'];
  return order.flatMap((s) => lines.filter((l) => l.sec === s));
}

const ddmmyy = (iso: string) => {
  const [y, m, d] = iso.split('-');
  return y && m && d ? `${d}.${m}.${y}` : iso;
};

/** Начальные параметры: форма по МКБ, стадия из диагноза, номер курса по прошлым курсам, миноксидил по полу. */
export function initialNosParams(c: Pick<DayCourse, 'template' | 'diagnosis' | 'sex' | 'fio'>, prevCount: number, icd = ''): NosParams {
  const d = nosDef(c.template);
  const dx = c.diagnosis || '';
  const code = icd || (dx.match(/\b([A-Z]\d{2}(?:\.\d)?)\b/i)?.[1] ?? '');
  const p: NosParams = {};
  if (d.forms) p.form = formForIcd(d.key, code);
  if (d.forms && !code) {
    const f = d.forms.find((x) => new RegExp(x.ru.slice(0, 5), 'i').test(dx));
    if (f) p.form = f.v;
  }
  if (d.stages) p.stage = /регресс/i.test(dx) && d.stages.includes('regr') ? 'regr' : /ремисс|стаб|стацион/i.test(dx) ? 'stat' : 'prog';
  if (d.course) p.course = Math.min(4, prevCount + 1) as NosParams['course'];
  if (d.minox) p.minox = sexOf(c) === 'F' ? '2' : '5';
  if (d.proc) p.proc = 'alt';
  return p;
}

/** Пол: из карты пациента, иначе по окончанию фамилии или отчества. */
export function sexOf(c: Pick<DayCourse, 'sex' | 'fio'>): 'M' | 'F' | '' {
  if (c.sex === 'M' || c.sex === 'F') return c.sex;
  const w = (c.fio || '').trim().toLowerCase().split(/\s+/);
  if (w.some((x) => /(ова|ева|ёва|ина|ая|кизи|қизи|кызы|овна|евна|ична)$/.test(x))) return 'F';
  if (w.some((x) => /(ов|ев|ёв|ин|ий|ович|евич|ич|ўғли|угли|оглы)$/.test(x))) return 'M';
  return '';
}

